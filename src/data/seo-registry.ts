export function getSeoPage(id: string): SeoPageRecord {
  const page = SEO_REGISTRY[id];
  if (!page) {
    throw new Error(`SEO page not found in registry: ${id}`);
  }
  return page;
}

export function getRelatedPages(pageId: string): SeoPageRecord[] {
  const page = SEO_REGISTRY[pageId];
  if (!page || !page.relatedPageIds) return [];
  return page.relatedPageIds
    .map((id) => SEO_REGISTRY[id])
    .filter((p): p is SeoPageRecord => Boolean(p));
}
